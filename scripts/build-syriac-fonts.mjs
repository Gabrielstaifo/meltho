// Converts the local Meltho (SyrCOM) Syriac fonts in assets/syriac-fonts/ to
// woff2 in public/fonts/ and generates src/styles/syriac-fonts.css.
//
// The Meltho fonts ship as .ttf; browsers are served the smaller woff2.
// Run manually (not part of the build): node scripts/build-syriac-fonts.mjs
//
// Requires fontTools + brotli, e.g. a project-local virtualenv:
//   python3 -m venv .venv && .venv/bin/pip install fonttools brotli
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, stat, writeFile } from 'node:fs/promises';

/**
 * Source fonts, in the order their @font-face rules are written.
 * `slug` is the file name stem in public/fonts/.
 */
const SOURCES = [
  { file: 'SyrCOMUrhoy.ttf', family: 'Serto Urhoy', weight: 400, slug: 'serto-urhoy' },
  { file: 'SyrCOMUrhoyBold.ttf', family: 'Serto Urhoy', weight: 700, slug: 'serto-urhoy' },
  { file: 'SyrCOMMalankara.ttf', family: 'Serto Malankara', weight: 400, slug: 'serto-malankara' },
];

const SRC_DIR = new URL('../assets/syriac-fonts/', import.meta.url);
const OUT_DIR = new URL('../public/fonts/', import.meta.url);
const CSS_OUT = new URL('../src/styles/syriac-fonts.css', import.meta.url);

/**
 * The Meltho fonts carry a vendor table whose tag contains a non-ASCII byte
 * (`TSI©`), which is invalid per the OpenType spec. fontTools writes table tags
 * as ASCII, so compressing them as-is crashes. Routing str -> bytes through
 * latin-1 keeps every tag byte intact, so the font is not modified.
 */
const CONVERT_SCRIPT = `
import sys
import fontTools.misc.sstruct as sstruct
from fontTools.misc.textTools import tobytes as _tobytes

def _tobytes_latin1(s, encoding="latin-1", errors="strict"):
    return _tobytes(s, encoding=encoding, errors=errors)

sstruct.tobytes = _tobytes_latin1

from fontTools.ttLib import TTFont

source, target = sys.argv[1], sys.argv[2]
font = TTFont(source)
font.flavor = "woff2"
font.save(target)
`;

/**
 * fontTools is a Python tool, so we need an interpreter that can import it.
 * Prefer the project-local virtualenv, then $PYTHON, then `python3`.
 */
function resolvePython() {
  const candidates = ['.venv/bin/python', process.env.PYTHON, 'python3'].filter(Boolean);
  for (const python of candidates) {
    try {
      execFileSync(python, ['-c', 'import fontTools'], { stdio: 'ignore' });
      return python;
    } catch {
      // Try the next candidate.
    }
  }
  throw new Error(
    'fontTools is not available. Create a virtualenv and install it:\n' +
      '  python3 -m venv .venv && .venv/bin/pip install fonttools brotli',
  );
}

const python = resolvePython();

await mkdir(OUT_DIR, { recursive: true });

const rules = [];

for (const { file, family, weight, slug } of SOURCES) {
  const input = new URL(file, SRC_DIR);
  if (!existsSync(input)) {
    throw new Error(`Missing source font: ${input.pathname}`);
  }

  const fileName = `${slug}-${weight}.woff2`;
  const output = new URL(fileName, OUT_DIR);

  execFileSync(python, ['-c', CONVERT_SCRIPT, input.pathname, output.pathname]);

  const { size } = await stat(output);
  console.log(`wrote ${fileName} (${(size / 1024).toFixed(1)} KB)`);

  rules.push(
    [
      '@font-face {',
      `  font-family: '${family}';`,
      '  font-style: normal;',
      `  font-weight: ${weight};`,
      '  font-display: swap;',
      `  src: url('/fonts/${fileName}') format('woff2');`,
      '}',
    ].join('\n'),
  );
}

const header = `/* Self-hosted Meltho (SyrCOM) Syriac webfonts. Generated by scripts/build-syriac-fonts.mjs — do not edit by hand.
 * Serto Malankara and Serto Urhoy are © Beth Mardutho: The Syriac Institute.
 * See assets/syriac-fonts/MELTHO-LICENSE.txt for the licence terms.
 */\n`;

await writeFile(CSS_OUT, `${header}\n${rules.join('\n\n')}\n`);
console.log(`wrote ${CSS_OUT.pathname} (${rules.length} @font-face rules)`);
