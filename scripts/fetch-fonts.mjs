// One-off helper: download self-hosted fonts (Amiri, Noto Sans Syriac) from
// Google Fonts and emit local @font-face rules. Run manually, not part of build.
// Usage: node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

const FAMILIES = [
  { query: 'Amiri:ital,wght@0,400;0,700;1,400', slug: 'amiri', keep: ['arabic', 'latin'] },
  { query: 'Noto+Sans+Syriac:wght@400;700', slug: 'noto-sans-syriac', keep: ['syriac', 'latin'] },
];

const OUT_DIR = new URL('../public/fonts/', import.meta.url);
const CSS_OUT = new URL('../src/styles/fonts.css', import.meta.url);

const STYLE = { normal: '', italic: 'italic' };

await mkdir(OUT_DIR, { recursive: true });

const rules = [];

for (const family of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Failed to fetch ${url}: ${res.status}`);
  const css = await res.text();

  const blocks = css.split('/*').slice(1);
  for (const block of blocks) {
    const subset = block.slice(0, block.indexOf('*/')).trim();
    if (!family.keep.includes(subset)) continue;

    const face = block.slice(block.indexOf('*/') + 2);
    const fontFamily = face.match(/font-family: '([^']+)'/)?.[1];
    const fontStyle = face.match(/font-style: (\w+)/)?.[1] ?? 'normal';
    const fontWeight = face.match(/font-weight: (\d+)/)?.[1] ?? '400';
    const srcUrl = face.match(/url\((https:[^)]+)\)/)?.[1];
    if (!fontFamily || !srcUrl) continue;

    const fileName = `${family.slug}-${fontWeight}${STYLE[fontStyle] ? `-${STYLE[fontStyle]}` : ''}-${subset}.woff2`;
    const bytes = Buffer.from(await (await fetch(srcUrl, { headers: { 'User-Agent': UA } })).arrayBuffer());
    await writeFile(new URL(fileName, OUT_DIR), bytes);

    const unicodeRange = face.match(/unicode-range: ([^;]+);/)?.[1];
    rules.push(
      [
        '@font-face {',
        `  font-family: '${fontFamily}';`,
        `  font-style: ${fontStyle};`,
        `  font-weight: ${fontWeight};`,
        '  font-display: swap;',
        `  src: url('/fonts/${fileName}') format('woff2');`,
        unicodeRange ? `  unicode-range: ${unicodeRange};` : '',
        '}',
      ]
        .filter(Boolean)
        .join('\n'),
    );
    console.log(`saved ${fileName} (${(bytes.length / 1024).toFixed(1)} KB)`);
  }
}

const header = `/* Self-hosted webfonts. Generated by scripts/fetch-fonts.mjs — do not edit by hand.\n * Amiri and Noto Sans Syriac are licensed under the SIL Open Font License 1.1.\n */\n`;
await writeFile(CSS_OUT, `${header}\n${rules.join('\n\n')}\n`);
console.log(`wrote ${CSS_OUT.pathname} (${rules.length} @font-face rules)`);
